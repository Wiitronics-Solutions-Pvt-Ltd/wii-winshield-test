import os
import io
import csv
import json
import zipfile
import random
import cv2

class YOLODatasetExporter:
    """
    Exports windshield coordinates and frame images in formats immediately usable
    for training and evaluating YOLO models.
    """

    def __init__(self, output_dir="output"):
        self.output_dir = os.path.abspath(output_dir)
        os.makedirs(self.output_dir, exist_ok=True)

    def export_full_yolo_zip(self, records_by_frame, frame_images, train_ratio=0.8, class_names=None):
        """
        Creates a ready-to-train YOLO dataset ZIP file.
        records_by_frame: dict { frame_idx: [detection_item, ...] }
        frame_images: dict { frame_idx: numpy_frame or filepath }
        train_ratio: float (e.g. 0.8 for 80% train / 20% val)
        class_names: list of class names (default: ["windshield"])
        """
        if class_names is None:
            class_names = ["windshield"]

        zip_buffer = io.BytesIO()

        frame_keys = sorted(list(records_by_frame.keys()))
        rng = random.Random(42)
        shuffled = list(frame_keys)
        rng.shuffle(shuffled)

        split_idx = int(len(shuffled) * train_ratio)
        train_frames = set(shuffled[:split_idx])
        val_frames = set(shuffled[split_idx:])
        if not val_frames and train_frames:
            val_frames = set(list(train_frames)[:1])

        with zipfile.ZipFile(zip_buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
            # 1. Create data.yaml
            data_yaml_content = f"""# Ultralytics YOLO dataset configuration
# Generated by WII-AI Windshield Extractor & YOLO Dataset Builder
path: ./yolo_windshield_dataset
train: train/images
val: val/images

# Classes
nc: {len(class_names)}
names:
"""
            for idx, name in enumerate(class_names):
                data_yaml_content += f"  {idx}: {name}\n"

            zf.writestr("yolo_windshield_dataset/data.yaml", data_yaml_content)

            # 2. Create README.md
            readme_content = f"""# Windshield YOLO Training Dataset

This dataset was generated using WII-AI Video Windshield Extractor.
Total annotated frames: {len(frame_keys)}
Train frames: {len(train_frames)}
Validation frames: {len(val_frames)}
Classes: {', '.join(class_names)}

## Quickstart: How to train with YOLOv8 / YOLOv11

1. Install Ultralytics:
```bash
pip install ultralytics
```

2. Train the model:
```bash
yolo detect train data=data.yaml model=yolov8n.pt epochs=50 imgsz=640 batch=16
```

3. Run inference on new traffic footage:
```bash
yolo detect predict model=runs/detect/train/weights/best.pt source="test_video.mp4"
```
"""
            zf.writestr("yolo_windshield_dataset/README.md", readme_content)

            # 3. Add images and labels
            for frame_idx, detections in records_by_frame.items():
                split = "train" if frame_idx in train_frames else "val"
                frame_name = f"frame_{frame_idx:06d}"

                # Write label .txt
                label_lines = []
                for d in detections:
                    yb = d.get("yolo_bbox")
                    if yb:
                        cid = yb.get("class_id", 0)
                        xc = yb.get("x_center", 0.0)
                        yc = yb.get("y_center", 0.0)
                        w = yb.get("width", 0.0)
                        h = yb.get("height", 0.0)
                        label_lines.append(f"{cid} {xc:.6f} {yc:.6f} {w:.6f} {h:.6f}")

                zf.writestr(
                    f"yolo_windshield_dataset/{split}/labels/{frame_name}.txt",
                    "\n".join(label_lines) + "\n"
                )

                # Write frame image
                img_data = frame_images.get(frame_idx)
                if img_data is not None:
                    if isinstance(img_data, str) and os.path.isfile(img_data):
                        with open(img_data, "rb") as f:
                            zf.writestr(f"yolo_windshield_dataset/{split}/images/{frame_name}.jpg", f.read())
                    elif hasattr(img_data, "shape"):  # numpy ndarray
                        ret, enc = cv2.imencode(".jpg", img_data, [int(cv2.IMWRITE_JPEG_QUALITY), 95])
                        if ret:
                            zf.writestr(f"yolo_windshield_dataset/{split}/images/{frame_name}.jpg", enc.tobytes())

        zip_buffer.seek(0)
        return zip_buffer

    def export_labels_only_zip(self, records_by_frame, class_names=None):
        """Exports only label .txt files and data.yaml as a ZIP archive."""
        if class_names is None:
            class_names = ["windshield"]

        zip_buffer = io.BytesIO()
        with zipfile.ZipFile(zip_buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
            yaml_content = f"""path: .
train: labels
val: labels

nc: {len(class_names)}
names:
"""
            for idx, name in enumerate(class_names):
                yaml_content += f"  {idx}: {name}\n"

            zf.writestr("data.yaml", yaml_content)

            for frame_idx, detections in records_by_frame.items():
                frame_name = f"frame_{frame_idx:06d}"
                lines = []
                for d in detections:
                    yb = d.get("yolo_bbox")
                    if yb:
                        lines.append(
                            f"{yb.get('class_id', 0)} {yb.get('x_center', 0.0):.6f} {yb.get('y_center', 0.0):.6f} {yb.get('width', 0.0):.6f} {yb.get('height', 0.0):.6f}"
                        )
                zf.writestr(f"labels/{frame_name}.txt", "\n".join(lines) + "\n")

        zip_buffer.seek(0)
        return zip_buffer

    def export_csv(self, flat_detections, video_meta=None):
        """
        Exports all extracted windshield coordinates as a structured CSV string.
        """
        output = io.StringIO()
        fieldnames = [
            "frame_index",
            "timestamp_sec",
            "image_filename",
            "class_id",
            "class_name",
            "x1_pixel",
            "y1_pixel",
            "x2_pixel",
            "y2_pixel",
            "box_width_px",
            "box_height_px",
            "frame_width",
            "frame_height",
            "x_center_norm",
            "y_center_norm",
            "width_norm",
            "height_norm",
            "top_left_x",
            "top_left_y",
            "top_right_x",
            "top_right_y",
            "bottom_right_x",
            "bottom_right_y",
            "bottom_left_x",
            "bottom_left_y",
            "confidence",
            "vehicle_type",
            "vehicle_bbox",
            "extraction_method"
        ]

        writer = csv.DictWriter(output, fieldnames=fieldnames)
        writer.writeheader()

        fw = video_meta.get("width", 1920) if video_meta else 1920
        fh = video_meta.get("height", 1080) if video_meta else 1080

        for d in flat_detections:
            f_idx = d.get("frame_idx", 0)
            yb = d.get("yolo_bbox", {})
            wb = d.get("windshield_bbox", [0, 0, 0, 0])
            c_px = {c.get("corner"): c for c in d.get("corners_px", [])}

            writer.writerow({
                "frame_index": f_idx,
                "timestamp_sec": d.get("timestamp_sec", 0.0),
                "image_filename": f"frame_{f_idx:06d}.jpg",
                "class_id": yb.get("class_id", 0),
                "class_name": yb.get("class_name", "windshield"),
                "x1_pixel": wb[0],
                "y1_pixel": wb[1],
                "x2_pixel": wb[2],
                "y2_pixel": wb[3],
                "box_width_px": wb[2] - wb[0],
                "box_height_px": wb[3] - wb[1],
                "frame_width": fw,
                "frame_height": fh,
                "x_center_norm": yb.get("x_center", 0.0),
                "y_center_norm": yb.get("y_center", 0.0),
                "width_norm": yb.get("width", 0.0),
                "height_norm": yb.get("height", 0.0),
                "top_left_x": c_px.get("top_left", {}).get("x", wb[0]),
                "top_left_y": c_px.get("top_left", {}).get("y", wb[1]),
                "top_right_x": c_px.get("top_right", {}).get("x", wb[2]),
                "top_right_y": c_px.get("top_right", {}).get("y", wb[1]),
                "bottom_right_x": c_px.get("bottom_right", {}).get("x", wb[2]),
                "bottom_right_y": c_px.get("bottom_right", {}).get("y", wb[3]),
                "bottom_left_x": c_px.get("bottom_left", {}).get("x", wb[0]),
                "bottom_left_y": c_px.get("bottom_left", {}).get("y", wb[3]),
                "confidence": d.get("confidence", 0.0),
                "vehicle_type": d.get("vehicle_type", "Car"),
                "vehicle_bbox": str(d.get("vehicle_bbox", [])),
                "extraction_method": d.get("extraction_method", "owlvit")
            })

        return output.getvalue()

    def export_json(self, flat_detections, video_meta=None):
        """
        Exports coordinates as a rich JSON format.
        """
        fw = video_meta.get("width", 1920) if video_meta else 1920
        fh = video_meta.get("height", 1080) if video_meta else 1080

        data = {
            "metadata": {
                "dataset_name": "Traffic Windshield Dataset",
                "classes": ["windshield"],
                "video": video_meta or {},
                "frame_dimensions": {"width": fw, "height": fh},
                "total_windshields_annotated": len(flat_detections)
            },
            "annotations": flat_detections
        }
        return json.dumps(data, indent=2)

    def export_crops_zip(self, crop_images_dict):
        """
        Exports cropped windshield images into a ZIP archive.
        crop_images_dict: dict { filename: image_bytes or numpy_array }
        """
        zip_buffer = io.BytesIO()
        with zipfile.ZipFile(zip_buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
            for fname, img in crop_images_dict.items():
                if isinstance(img, bytes):
                    zf.writestr(f"windshield_crops/{fname}", img)
                elif hasattr(img, "shape"):
                    ret, enc = cv2.imencode(".jpg", img, [int(cv2.IMWRITE_JPEG_QUALITY), 95])
                    if ret:
                        zf.writestr(f"windshield_crops/{fname}", enc.tobytes())
        zip_buffer.seek(0)
        return zip_buffer
